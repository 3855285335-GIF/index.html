// Exercises the permission migrations and their rollback on disposable PostgreSQL.
import assert from 'node:assert/strict';
import { readdirSync, readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const directory = name => new URL('../supabase/' + name + '/', import.meta.url);
const migrations = readdirSync(directory('migrations')).filter(name => name.endsWith('.sql')).sort();
const sql = (folder, name) => readFileSync(new URL(name, directory(folder)), 'utf8');
const catalog = {
  anon: ['chat_group_members', 'chat_groups', 'conversations', 'friend_requests', 'friendships',
    'group_invites', 'messages', 'profiles', 'search_cache', 'search_prefs', 'search_usage'],
  authenticated: ['chat_backgrounds', 'chat_group_members', 'chat_groups', 'conversations',
    'friend_requests', 'friendships', 'group_files', 'group_invites', 'group_notices', 'messages',
    'moment_comments', 'moment_likes', 'moment_mentions', 'moment_views', 'moments', 'profiles',
    'search_cache', 'search_prefs', 'search_usage', 'stickers', 'user_devices', 'user_mutes']
};
const alice = '11111111-1111-4111-8111-111111111111';
const bob = '22222222-2222-4222-8222-222222222222';
const validSession = '33333333-3333-4333-8333-333333333333';
const sb = (sub, session_id) => JSON.stringify({ sub, session_id, role: 'authenticated' });
const claims = (sub, sid) => db.query("select set_config('request.jwt.claims', $1, false)", [sb(sub, sid)]);
const functionSql = sql('rollback', migrations.find(name => name.includes('function_privileges')));
const friendFile = migrations.find(name => name.includes('friend_request_transitions'));
const friendOld = sql('rollback', friendFile).split('CREATE OR REPLACE FUNCTION', 2)[0];
const friendDefinitions = sql('rollback', friendFile).slice(friendOld.length).replace(/\ncommit;\s*$/, '');
const triggerList = /grant execute on function\s+([\s\S]+?)\s+to public/.exec(functionSql)[1].split(',').map(s => s.trim());
try {
  await db.exec(`
    create role anon;
    create role authenticated;
    create role service_role bypassrls;
    create schema auth;
    create schema storage;
    grant usage on schema auth, storage to anon, authenticated, service_role;
    create function auth.jwt() returns jsonb language sql stable as $$
      select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb
    $$;
    create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
    create function auth.role() returns text language sql stable as $$ select auth.jwt()->>'role' $$;
    create table auth.sessions (id uuid primary key, user_id uuid);
    insert into auth.sessions values ('${validSession}', '${alice}');
    create table public.profiles (
      id uuid primary key, account_id text unique, nickname text, avatar_url text,
      signature text, created_at timestamptz, bg_url text, cover_url text, bubble_color text,
      devices jsonb, mutes jsonb, moments_seen_at timestamptz, kick_at timestamptz
    );
    alter table public.profiles enable row level security;
    create policy profiles_select on public.profiles for select to authenticated using (true);
    create policy profiles_update on public.profiles for update to authenticated
      using (id = auth.uid()) with check (id = auth.uid());
    create policy profiles_insert on public.profiles for insert to authenticated with check (id = auth.uid());
    insert into public.profiles (id, account_id, nickname, kick_at, devices)
      values ('${alice}', 'alice', 'Alice', '2026-10-01Z', '{"alice":"private"}'),
             ('${bob}', 'bob', 'Bob', '2026-10-02Z', '{"bob":"private"}');
    create function public.my_acc() returns text language sql stable security definer as $$
      select account_id from public.profiles where id = auth.uid()
    $$;
    create table public.friend_requests (
      id bigint generated by default as identity primary key, from_acc text, to_acc text,
      from_name text, status text, created_at timestamptz default now()
    );
    create table public.friendships (owner_acc text, friend_acc text, primary key (owner_acc, friend_acc));
    create table public.conversations (owner_acc text, conv_key text, peer_acc text, primary key (owner_acc, conv_key));
    alter table public.friend_requests enable row level security;
    create policy fr_select on public.friend_requests for select to authenticated
      using (to_acc = public.my_acc() or from_acc = public.my_acc());
    create policy fr_update on public.friend_requests for update to authenticated
      using (to_acc = public.my_acc()) with check (to_acc = public.my_acc());
    grant select, update on public.friend_requests to anon, authenticated;
    create publication supabase_realtime for table public.profiles;
    create function public.session_alive() returns boolean language sql stable security definer as $$ select true $$;
    create function public.bootstrap() returns jsonb language sql stable security definer as $$
      select to_jsonb(p) from public.profiles p where p.account_id = public.my_acc()
    $$;
    create function storage.foldername(name text) returns text[] language sql immutable as $$
      select (string_to_array(name,'/'))[1:cardinality(string_to_array(name,'/'))-1]
    $$;
    create function storage.filename(name text) returns text language sql immutable as $$
      select (string_to_array(name,'/'))[cardinality(string_to_array(name,'/'))]
    $$;
    create table storage.buckets (id text primary key, public boolean, file_size_limit bigint, allowed_mime_types text[]);
    insert into storage.buckets values ('chat-media', true, 52428800, null);
    create table storage.objects (name text primary key, bucket_id text);
    insert into storage.objects values ('alice/old.jpg', 'chat-media'), ('bob/old.jpg', 'chat-media');
    alter table storage.objects enable row level security;
    create policy "chat-media insert own" on storage.objects for insert to authenticated
      with check (bucket_id = 'chat-media' and (storage.foldername(name))[1] = public.my_acc());
    create policy "chat-media select own" on storage.objects for select to authenticated
      using (bucket_id = 'chat-media' and (storage.foldername(name))[1] = public.my_acc());
    create policy "chat-media delete own" on storage.objects for delete to authenticated
      using (bucket_id = 'chat-media' and (storage.foldername(name))[1] = public.my_acc());
    create policy "media insert" on storage.objects for insert to public
      with check (bucket_id = 'chat-media' and auth.role() = 'authenticated');
    create policy "media read" on storage.objects for select to public using (bucket_id = 'chat-media');
    grant select, insert, update on public.profiles to anon, authenticated, service_role;
    grant select, insert, delete on storage.objects to anon, authenticated, service_role;
    alter default privileges for role postgres in schema public grant truncate on tables to anon, authenticated;
  `);
  const names = [...new Set(Object.values(catalog).flat())];
  for (const name of names.filter(name => !['profiles','friend_requests','conversations','friendships'].includes(name))) await db.exec('create table public.' + name + '(id int)');
  // Match the catalog's asymmetrical grants and independently snapshot it before applying.
  await db.exec('revoke truncate on all tables in schema public from anon, authenticated');
  for (const [role, tables] of Object.entries(catalog)) await db.exec('grant truncate on table ' + tables.join(', ') + ' to ' + role);
  await db.exec(`
    create function public.conv_key_of(text,text) returns text language sql as $$ select $1 || $2 $$;
    create function public.chatter_schema() returns integer language sql as $$ select 8 $$;
    grant all on public.messages to service_role;
  `);
  await db.exec(friendDefinitions);
  for (const signature of triggerList) {
    await db.exec(`create function ${signature} returns trigger language plpgsql security definer as $$ begin return new; end $$; grant execute on function ${signature} to anon, authenticated;`);
  }
  const acl = async () => (await db.query(`
    select relname, has_table_privilege('anon',oid,'truncate') as anon,
      has_table_privilege('authenticated',oid,'truncate') as authenticated
    from pg_class where relnamespace = 'public'::regnamespace and relkind = 'r' order by relname
  `)).rows;
  const original = await acl();
  for (const name of migrations) await db.exec(sql('migrations', name));
  assert.ok((await acl()).every(x => !x.anon && !x.authenticated));
  await db.exec('create table public.after_repair(id int)');
  const privileges = (await db.query(`select has_table_privilege('authenticated','after_repair','truncate') as client,
    has_table_privilege('service_role','messages','truncate') as server`)).rows[0];
  assert.deepEqual(privileges, { client: false, server: true });
  await db.exec('drop table public.after_repair');
  assert.equal((await db.query("select has_function_privilege('authenticated','public.guard_account_id()','execute') as allowed")).rows[0].allowed, false);
  const publication = (await db.query("select attnames from pg_publication_tables where tablename='profiles'")).rows[0].attnames;
  assert.ok(!publication.includes('kick_at') && publication.includes('nickname'));

  await claims(alice, validSession);
  await db.exec('set role authenticated');
  const visible = await db.query('select account_id, nickname from public.profiles order by account_id');
  assert.deepEqual(visible.rows.map(r => r.account_id), ['alice', 'bob']);
  for (const name of ['kick_at', 'mutes', 'devices', 'moments_seen_at']) {
    await assert.rejects(db.query('select ' + name + ' from public.profiles'), { code: '42501' });
  }
  assert.equal((await db.query("select bootstrap()->'devices' as devices")).rows[0].devices.alice, 'private');
  assert.equal(new Date((await db.query('select my_kick_at() as t')).rows[0].t).toISOString(), '2026-10-01T00:00:00.000Z');
  assert.equal((await db.query("update profiles set nickname='Alice new' where id=auth.uid() returning id")).rows.length, 1);
  assert.equal((await db.query("select send_friend_request('bob') as result")).rows[0].result, 'ok');
  assert.equal((await db.query("select send_friend_request('bob') as result")).rows[0].result, 'exists');
  assert.equal((await db.query("update friend_requests set status='declined' returning id")).rows.length, 0);
  await claims(bob);
  await assert.rejects(db.query("update friend_requests set status='accepted'"), { code: '42501' });
  await assert.rejects(db.query("update friend_requests set from_acc='stranger'"), { code: '42501' });
  const declined = await db.query("update friend_requests set status='declined' returning id");
  assert.equal(declined.rows.length, 1);
  await assert.rejects(db.query('select accept_friend_request($1)', [String(declined.rows[0].id)]), /request not found/);
  await claims(alice, validSession);
  assert.equal((await db.query("select send_friend_request('bob') as result")).rows[0].result, 'ok');
  await claims(bob);
  assert.equal((await db.query("select send_friend_request('alice') as result")).rows[0].result, 'accepted');
  assert.equal((await db.query("select status from friend_requests")).rows[0].status, 'accepted');
  await claims(alice, validSession);
  await db.exec("insert into storage.objects values ('alice/new.jpg','chat-media')");
  for (const name of ['bob/unauthorized.jpg', 'alice/nested/file.png', 'alice/', 'alice/..']) {
    await assert.rejects(db.query("insert into storage.objects values ($1,'chat-media')", [name]), { code: '42501' });
  }
  assert.equal((await db.query("select name from storage.objects where name like 'bob/%'")).rows.length, 0);
  assert.equal((await db.query("delete from storage.objects where name='bob/old.jpg' returning name")).rows.length, 0);
  await claims(bob, validSession);
  assert.deepEqual((await db.query('select session_alive() as alive, my_acc() as acc')).rows[0], { alive: false, acc: null });
  await claims(bob, 'malformed-session');
  assert.equal((await db.query('select session_alive() as alive')).rows[0].alive, false);
  await claims(bob);
  assert.equal((await db.query('select session_alive() as alive')).rows[0].alive, true);
  await db.exec('set role anon');
  await assert.rejects(db.query('select my_kick_at()'), { code: '42501' });
  assert.equal((await db.query('select nickname from profiles')).rows.length, 0);
  await db.exec('reset role');
  const bucket = (await db.query('select public, file_size_limit, allowed_mime_types from storage.buckets')).rows[0];
  assert.equal(bucket.public, true);
  assert.equal(Number(bucket.file_size_limit), 52428800);
  assert.ok(bucket.allowed_mime_types.includes('image/gif') && !bucket.allowed_mime_types.includes('text/html'));

  for (const name of [...migrations].reverse()) await db.exec(sql('rollback', name));
  assert.deepEqual(await acl(), original);
  assert.equal((await db.query('select allowed_mime_types from storage.buckets')).rows[0].allowed_mime_types, null);
  assert.equal((await db.query("select has_function_privilege('authenticated','public.guard_account_id()','execute') as allowed")).rows[0].allowed, true);
  const rolledBack = (await db.query("select attnames from pg_publication_tables where tablename='profiles'")).rows[0].attnames;
  assert.ok(rolledBack.includes('kick_at'));
  await claims(alice, validSession);
  await db.exec('set role authenticated');
  assert.equal((await db.query("select devices from profiles where account_id='bob'")).rows[0].devices.bob, 'private');
  assert.equal((await db.query('select count(*)::int as n from storage.objects')).rows[0].n, 3);
  console.log('✅ 权限、资料与 Realtime 列、上传路径、会话检查、好友状态、旧数据及全部回滚 SQL 通过');
} finally {
  await db.close();
}
